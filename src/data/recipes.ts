// 比對引擎：根據用戶選的食材找出最匹配的食譜
// ============================================================
export function findBestRecipe(selectedIngredients: string[]): Recipe | null {
  if (!selectedIngredients.length) return null

  // 先把用戶的食材正規化
  const userSet = new Set(selectedIngredients.map(i => i.trim()))

  let bestRecipe: Recipe | null = null
  let bestScore = -1

  for (const recipe of recipes) {
    const recipeSet = new Set(recipe.ingredientTags.map(i => i.trim()))
    let matchCount = 0

    for (const item of userSet) {
      if (recipeSet.has(item)) matchCount++
    }

    // 分數 = 配對數 + (配對數/用戶食材數)*0.5 bonus（鼓勵高覆蓋率）
    const coverage = userSet.size > 0 ? matchCount / userSet.size : 0
    const score = matchCount + coverage * 0.5

    if (score > bestScore) {
      bestScore = score
      bestRecipe = recipe
    }
  }

  return bestRecipe
}

// 取得所有食譜（給隨機挑選用）
export function getAllRecipes(): Recipe[] {
  return recipes
}

// 隨機食譜
export function getRandomRecipe(): Recipe {
  return recipes[Math.floor(Math.random() * recipes.length)]
}
